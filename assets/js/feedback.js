/* MeasureMarks calculator issue reporting; user-controlled email, no background data transfer. */
(() => {
 'use strict';
 const host=document.querySelector('.results'),controls=document.querySelector('.controls');
 if(!host||!controls)return;
 const block=document.createElement('div');
 block.className='mm-feedback';
 block.innerHTML='<button type="button" class="mm-feedback-trigger" aria-expanded="false" aria-controls="mm-feedback-form">Found an incorrect measurement? Report a problem <span aria-hidden="true">↗</span></button><div id="mm-feedback-form" class="mm-feedback-panel" hidden><h3>Report a calculator problem</h3><p>Tell us what went wrong. Your current settings and displayed results will be included in the email.</p><form class="mm-feedback-form"><label>What went wrong?<textarea name="problem" required rows="3" maxlength="2500" placeholder="Example: The second center mark appears 1/4 inch too far right."></textarea></label><label>What did you expect? <span>(optional)</span><textarea name="expected" rows="2" maxlength="1500" placeholder="Explain the result you expected."></textarea></label><label>Your email address <span>(optional)</span><input name="reply" type="email" autocomplete="email" maxlength="180" placeholder="For follow-up, if needed"></label><label class="mm-feedback-check"><input name="include" type="checkbox" checked> Include calculator inputs and visible results</label><p class="mm-feedback-help">This opens your email app with a prepared message to contact@measuremarks.com. Review it and press Send there. No report is submitted automatically.</p><div class="mm-feedback-actions"><button type="submit">Prepare email report</button><button type="button" class="mm-feedback-cancel">Cancel</button></div></form></div>';
 host.appendChild(block);
 const trigger=block.querySelector('.mm-feedback-trigger'),panel=block.querySelector('.mm-feedback-panel'),form=block.querySelector('form');
 function close(){panel.hidden=true;trigger.setAttribute('aria-expanded','false');trigger.focus();}
 trigger.addEventListener('click',()=>{const opening=panel.hidden;panel.hidden=!opening;trigger.setAttribute('aria-expanded',String(opening));if(opening)form.elements.problem.focus();});
 block.querySelector('.mm-feedback-cancel').addEventListener('click',close);
 function labelOf(el){
   const container=el.closest('label');
   if(container){const clone=container.cloneNode(true);clone.querySelectorAll('input,select,textarea').forEach(n=>n.remove());const t=clone.textContent.replace(/\s+/g,' ').trim();if(t)return t;}
   return el.getAttribute('aria-label')||el.name||el.id||'Input';
 }
 function snapshot(){
   const lines=[];
   controls.querySelectorAll('input,select,textarea').forEach(el=>{
     if(el.disabled || el.type==='hidden'||el.type==='button'||el.type==='submit')return;
     if(el.type==='radio'&&!el.checked)return;
     if((el.type==='checkbox')&&!el.checked)return;
     if(el.closest('[hidden]'))return;
     // Skip controls in sections not applicable to the current layout.
     const hiddenAncestor=el.closest('.hidden');
     if(hiddenAncestor)return;
     const val=el.tagName==='SELECT'?el.selectedOptions[0]?.textContent:el.type==='checkbox'?'Yes':el.value;
     if(val!==undefined&&val!=='')lines.push(labelOf(el)+': '+String(val));
   });
   const mode=document.querySelector('.seg.active[data-units]')?.dataset.units||'imperial';
   const outputs=[];
   for(const id of ['resultTitle','resultNote','statA','statB','statC','marksTitle']){
     const el=document.getElementById(id);
     if(el?.textContent.trim())outputs.push((id==='resultNote'?'Explanation':id)+': '+el.textContent.trim().replace(/\s+/g,' '));
   }
   const marks=[...document.querySelectorAll('#marks .mark')].map(e=>e.textContent.trim().replace(/\s+/g,' ')).filter(Boolean);
   if(marks.length)outputs.push('Installation marks:\n'+marks.slice(0,80).map((m,i)=>(i+1)+'. '+m).join('\n')+(marks.length>80?'\n(Additional marks omitted)':''));
   return {inputs:['Units: '+mode,...lines],outputs};
 }
 form.addEventListener('submit',ev=>{
   ev.preventDefault();
   if(!form.reportValidity())return;
   const project=document.querySelector('h1')?.textContent.trim()||document.title;
   const data=new FormData(form);
   const sections=['MeasureMarks calculator issue','Calculator: '+project,'Page: '+location.href,'','What went wrong:\n'+String(data.get('problem')||'').trim(),'','Expected result:\n'+(String(data.get('expected')||'').trim()||'Not provided'),'','Reply-to address: '+(String(data.get('reply')||'').trim()||'Not provided')];
   if(data.get('include')){const s=snapshot();sections.push('','CALCULATOR SETTINGS',...s.inputs,'','DISPLAYED RESULTS',...s.outputs);}
   sections.push('','Generated by MeasureMarks Report a Problem. Please attach a screenshot if helpful.');
   const subject='MeasureMarks problem: '+project;
   const url='mailto:contact@measuremarks.com?subject='+encodeURIComponent(subject)+'&body='+encodeURIComponent(sections.join('\n'));
   // A URL can exceed mail-client limits on unusually large layouts.
   if(url.length>18000){alert('This report is too long for some email apps. Uncheck "Include calculator inputs and visible results" and try again.');return;}
   window.location.href=url;
 });
})();